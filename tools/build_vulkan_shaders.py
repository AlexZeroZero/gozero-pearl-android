"""Compile the exact packed-s8 GEMM/milestone/jackpot shader into the signed worker."""
from pathlib import Path
import subprocess,sys,struct,os,platform
root=Path(__file__).resolve().parents[1]
host={'Windows':'windows-x86_64','Linux':'linux-x86_64','Darwin':'darwin-x86_64'}[platform.system()]
ndk=Path(os.environ.get('ANDROID_NDK_HOME','D:/Android/Sdk/ndk/28.2.13676358'))
shaderc=Path(sys.argv[1]) if len(sys.argv)>1 else ndk/'shader-tools'/host
exe='.exe' if os.name=='nt' else ''
out=root/'native/cppminer/src/opencl/vulkan';out.mkdir(exist_ok=True)
header=['// Generated by tools/build_vulkan_shaders.py; signed-s8 arithmetic, 32 milestones.','#pragma once','#include <cstdint>']
for mm,nn in [(64,64),(128,128),(64,256)]:
 src='''#version 450
#extension GL_EXT_spirv_intrinsics : require
spirv_instruction(extensions=["SPV_KHR_integer_dot_product"], capabilities=[6018,6019], id=4450)
int packedDot(int a,int b,spirv_literal int format);
layout(set=0,binding=0,std430) readonly buffer A { uint a[]; };
layout(set=0,binding=1,std430) readonly buffer B { uint b[]; };
layout(set=0,binding=2,std430) buffer Control { uint ctrl[]; };
layout(push_constant) uniform Params {uint m;uint n;uint base;} p;
uint rotr(uint v,int n){return (v>>n)|(v<<(32-n));}
void g(inout uint v[16],int a,int b,int c,int d,uint x,uint y){
v[a]+=v[b]+x;v[d]=rotr(v[d]^v[a],16);v[c]+=v[d];v[b]=rotr(v[b]^v[c],12);
v[a]+=v[b]+y;v[d]=rotr(v[d]^v[a],8);v[c]+=v[d];v[b]=rotr(v[b]^v[c],7);}
bool jackpot(uint msg[16]){
 uint v[16]=uint[16](ctrl[0],ctrl[1],ctrl[2],ctrl[3],ctrl[4],ctrl[5],ctrl[6],ctrl[7],0x6A09E667u,0xBB67AE85u,0x3C6EF372u,0xA54FF53Au,0u,0u,64u,0x1Bu);
 const int perm[16]=int[16](2,6,3,10,7,0,4,13,1,11,12,5,9,14,15,8);
 for(int r=0;r<7;r++){
  g(v,0,4,8,12,msg[0],msg[1]);g(v,1,5,9,13,msg[2],msg[3]);g(v,2,6,10,14,msg[4],msg[5]);g(v,3,7,11,15,msg[6],msg[7]);
  g(v,0,5,10,15,msg[8],msg[9]);g(v,1,6,11,12,msg[10],msg[11]);g(v,2,7,8,13,msg[12],msg[13]);g(v,3,4,9,14,msg[14],msg[15]);
  if(r<6){uint t[16];for(int i=0;i<16;i++)t[i]=msg[perm[i]];for(int i=0;i<16;i++)msg[i]=t[i];}
 }
 for(int i=7;i>=0;i--){uint h=v[i]^v[i+8];if(h<ctrl[8+i])return true;if(h>ctrl[8+i])return false;}
 return true;
}
'''
 src+=f'layout(local_size_x={mm//4*(nn//8)}) in;\nvoid main(){{\nuint lid=gl_LocalInvocationID.x;uint tr=lid%{mm//4};uint tc=lid/{mm//4};\nuint im=(p.base+gl_WorkGroupID.x)%(p.m/{mm});uint jm=(p.base+gl_WorkGroupID.x)/(p.m/{mm});\n'
 src+='uint msg[16];for(int i=0;i<16;i++)msg[i]=0;\n'
 for i in range(4):
  for j in range(8):src+=f'int c{i}{j}=0;\n'
 src+='for(uint ms=0;ms<32;ms++){for(uint kg=0;kg<32;kg++){\n'
 for i in range(4):src+=f'int av{i}=int(a[im*{mm*1024}+ms*{32*mm}+kg*{mm}+tr*4+{i}]);\n'
 for j in range(8):src+=f'int bv{j}=int(b[jm*{nn*1024}+ms*{32*nn}+kg*{nn}+tc*8+{j}]);\n'
 for i in range(4):
  for j in range(8):src+=f'c{i}{j}+=packedDot(av{i},bv{j},0);\n'
 src+='}\nuint x=uint('+'^'.join(f'c{i}{j}' for i in range(4) for j in range(8))+');\nmsg[ms%16]^=ms<16?((x<<13)|(x>>19)):x;\n}\n'
 src+=f'if(jackpot(msg)&&atomicCompSwap(ctrl[16],0,1)==0){{ctrl[17]=im*{mm}+tr*4;ctrl[18]=jm*{nn}+tc*8;}}\n}}\n'
 name=f'pearl-int8-{mm}x{nn}';(out/(name+'.comp')).write_text(src)
 spv=out/(name+'.spv')
 subprocess.run([str(shaderc/('glslc'+exe)),'--target-env=vulkan1.3','-O',str(out/(name+'.comp')),'-o',str(spv)],check=True)
 subprocess.run([str(shaderc/('spirv-val'+exe)),'--target-env','vulkan1.3',str(spv)],check=True)
 words=struct.unpack('<'+'I'*(spv.stat().st_size//4),spv.read_bytes())
 header.append(f'static const uint32_t pearl_vk_{mm}_{nn}[]={{')
 header+=['  '+','.join(f'0x{v:08x}u' for v in words[i:i+8])+',' for i in range(0,len(words),8)]
 header.append('};')
(out/'pearl_spv.hpp').write_text('\n'.join(header)+'\n')
